"""Compare syllable counts of new lyrics against the original, line by line.

New lyrics go in lyrics/new-lyrics.txt: one line per original line, same order.
Blank lines are ignored; section tags like [Chorus] label the lines below them.

    uv run python pace_check.py [path/to/new-lyrics.txt]

Prints the comparison and writes it to lyrics/pace-report.md.

Syllables are estimated with a heuristic plus the EXACT table below; when a
count looks wrong, add the word to EXACT. Acronyms are spelled out (pron.py rules).
"""
import json
import re
import sys

import common
from pron import PRON, pron

NEW_LYRICS = common.PROJECT / "lyrics" / "new-lyrics.txt"
REPORT = common.PROJECT / "lyrics" / "pace-report.md"
TOLERANCE = 1  # syllables a line may differ before it is flagged

# words the heuristic gets wrong (lowercase, after pron.py splitting)
EXACT = {
    "rearranging": 4, "there's": 1, "safety": 2, "hundred": 2, "foretold": 2,
    "absolutely": 4, "retrying": 3, "linkedin": 2, "linkedin's": 2, "changelog": 2, "vibes": 1,
}


def syllables(word: str) -> int:
    w = word.lower().strip("'")
    if not w:
        return 0
    if w in EXACT:
        return EXACT[w]
    if len(w) == 1:
        return 1
    n = len(re.findall(r"[aeiouy]+", w))
    if w.endswith("e") and not w.endswith(("le", "ee", "ye")) and n > 1:
        n -= 1  # silent e: "make", "alive"
    if re.search(r"[^aeiou]ed$", w) and not re.search(r"[td]ed$", w) and n > 1:
        n -= 1  # "rearranged" -> no extra syllable
    return max(n, 1)


def spell_out(token: str) -> list[str]:
    # all-caps tokens with no pron.py entry are read letter by letter ("HR's" -> h r)
    if token in PRON:
        return pron(token)
    m = re.fullmatch(r"[^A-Za-z]*([A-Z]{2,})(?:'s)?[^A-Za-z]*", token)
    if m:
        return list(m.group(1).lower())
    return pron(token)


def line_syllables(text: str) -> int:
    return sum(syllables(p) for tok in text.split() for p in spell_out(tok))


def load_new(path) -> list[tuple[str, str]]:
    """-> [(section, line)]"""
    out, section = [], ""
    for l in path.read_text(encoding="utf-8").splitlines():
        l = l.strip()
        if m := re.fullmatch(r"\[(.*)\]", l):
            section = m.group(1)
        elif l:
            out.append((section, l))
    return out


def main():
    path = common.Path(sys.argv[1]) if len(sys.argv) > 1 else NEW_LYRICS
    orig = json.loads((common.DATA / "lyrics.json").read_text())["lines"]
    new = load_new(path)

    md = ["# Pace report", "", f"Generated by `analysis/pace_check.py` from `{path.name}`. "
          f"Target = syllables in the original line; lines off by more than {TOLERANCE} are marked ❌.", ""]
    if len(new) != len(orig):
        warn = f"WARNING: {len(new)} new lines vs {len(orig)} original lines; pairing by order"
        print(warn + "\n")
        md += [f"> {warn}", ""]

    flagged, section = 0, None
    print(f"{'#':>2} {'sec':>5} {'old':>3} {'new':>3} {'diff':>4}  original  ->  new")
    for i, (o, (sec, n)) in enumerate(zip(orig, new)):
        so, sn = line_syllables(o["text"]), line_syllables(n)
        d = sn - so
        bad = abs(d) > TOLERANCE
        flagged += bad
        dur = o["end"] - o["start"]
        print(f"{i:>2} {dur:5.1f} {so:>3} {sn:>3} {d:>+4}{' !!' if bad else ''}  {o['text']}  ->  {n}")
        if sec != section:
            section = sec
            md += ["", f"## {sec or '(no section)'}", "",
                   "| # | sec | target | yours | diff | | original | yours |",
                   "|--:|--:|--:|--:|--:|:-:|---|---|"]
        md.append(f"| {i} | {dur:.1f} | {so} | {sn} | {d:+d} | {'❌' if bad else '✅'} | {o['text']} | {n} |")

    summary = f"{flagged} line(s) off by more than {TOLERANCE} syllable(s)"
    print(f"\n{summary}")
    REPORT.write_text("\n".join(md + ["", f"**{summary}**", ""]), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(common.PROJECT)}")


if __name__ == "__main__":
    main()
